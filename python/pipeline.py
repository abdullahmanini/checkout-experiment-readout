"""Load the raw CSVs into SQLite, build staging and marts, then run the data tests.

Usage: python3 python/pipeline.py
Writes outputs/experiment.db, outputs/test_results.json and docs/test_results.md.
Exits with status 1 if any error-severity test fails; warnings are reported, not fatal.
"""
import csv
import json
import re
import sqlite3
import sys
from pathlib import Path

import experiment_model as m

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "data" / "raw"
OUT = ROOT / "outputs"
DB = OUT / "experiment.db"
SOURCES = ["assignments", "customers", "checkout_events", "payment_attempts", "refunds", "disputes"]


def load_raw(conn):
    """Land each CSV as an all-text table, the way it arrives."""
    counts = {}
    for name in SOURCES:
        with open(RAW / f"{name}.csv", newline="") as f:
            reader = csv.reader(f)
            header = next(reader)
            rows = list(reader)
        conn.execute(f"DROP TABLE IF EXISTS raw_{name}")
        conn.execute(f"CREATE TABLE raw_{name} ({', '.join(c + ' TEXT' for c in header)})")
        conn.executemany(f"INSERT INTO raw_{name} VALUES ({', '.join('?' * len(header))})", rows)
        counts[f"raw_{name}"] = len(rows)
    conn.execute("DROP TABLE IF EXISTS params")
    conn.execute("CREATE TABLE params (experiment_id TEXT, start_at TEXT, end_at TEXT, data_cutoff TEXT)")
    conn.execute("INSERT INTO params VALUES (?, ?, ?, ?)", (
        m.EXPERIMENT_ID, m.START.strftime("%Y-%m-%d %H:%M:%S"), m.END.strftime("%Y-%m-%d %H:%M:%S"),
        m.DATA_CUTOFF.strftime("%Y-%m-%d %H:%M:%S")))
    # Seed table: builds the investigation tied to the SRM (see docs/readout.md).
    conn.execute("DROP TABLE IF EXISTS known_bad_builds")
    conn.execute("CREATE TABLE known_bad_builds (app_version TEXT PRIMARY KEY, reason TEXT)")
    conn.executemany("INSERT INTO known_bad_builds VALUES (?, ?)",
                     [(v, "checkout_module_logging_bug") for v in m.BUGGY_APP_VERSIONS])
    conn.commit()
    return counts


def parse_tests(path):
    """Split tests.sql on '-- test:' blocks, reading severity and description from the header comments."""
    tests = []
    for block in re.split(r"^-- test: ", path.read_text(), flags=re.M)[1:]:
        name, rest = block.split("\n", 1)
        severity = re.search(r"^-- severity: (\w+)", rest, flags=re.M).group(1)
        checks = re.search(r"^-- checks: (.+)$", rest, flags=re.M).group(1)
        sql = "\n".join(line for line in rest.splitlines() if not line.startswith("--")).strip()
        tests.append({"name": name.strip(), "severity": severity, "checks": checks, "sql": sql})
    return tests


def run_tests(conn):
    results = []
    for t in parse_tests(ROOT / "sql" / "tests.sql"):
        cur = conn.execute(t["sql"])
        cols = [c[0] for c in cur.description]
        rows = [dict(zip(cols, r)) for r in cur.fetchall()]
        results.append({"name": t["name"], "severity": t["severity"], "checks": t["checks"],
                        "status": "pass" if not rows else "fail", "failing_rows": len(rows), "sample": rows[:8]})
    return results


def to_markdown(results, counts):
    lines = ["# Data test results", "", "Generated by `python/pipeline.py`. Zero failing rows means a test passes.", "",
             "| Test | Severity | Status | Failing rows | What it checks |", "|---|---|---|---:|---|"]
    for r in results:
        lines.append(f"| `{r['name']}` | {r['severity']} | {r['status']} | {r['failing_rows']:,} | {r['checks']} |")
    lines += ["", "## Failing rows (first eight per test)", ""]
    for r in results:
        if r["sample"]:
            cols = list(r["sample"][0].keys())
            lines += [f"### {r['name']}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
            lines += ["| " + " | ".join(str(row[c]) for c in cols) + " |" for row in r["sample"]]
            lines.append("")
    lines += ["## Table row counts", "", "| Table | Rows |", "|---|---:|"]
    lines += [f"| {k} | {v:,} |" for k, v in counts.items()]
    return "\n".join(lines) + "\n"


def main():
    OUT.mkdir(exist_ok=True)
    if DB.exists():
        DB.unlink()
    conn = sqlite3.connect(DB)
    counts = load_raw(conn)
    for layer in ("staging", "marts"):
        conn.executescript((ROOT / "sql" / f"{layer}.sql").read_text())
    conn.commit()
    for table in ["stg_checkout_events", "fct_checkout_sessions", "fct_orders", "exp_customers"]:
        counts[table] = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchone()[0]

    results = run_tests(conn)
    (OUT / "test_results.json").write_text(json.dumps({"tests": results, "row_counts": counts}, indent=2))
    (ROOT / "docs" / "test_results.md").write_text(to_markdown(results, counts))
    for r in results:
        flag = "ok  " if r["status"] == "pass" else ("WARN" if r["severity"] == "warn" else "FAIL")
        print(f"{flag}  {r['name']:<40} {r['failing_rows']:>6,} failing rows")
    errors = [r for r in results if r["status"] == "fail" and r["severity"] == "error"]
    if errors:
        print(f"\n{len(errors)} error-level test(s) failed; stopping before analysis.")
        sys.exit(1)


if __name__ == "__main__":
    main()
